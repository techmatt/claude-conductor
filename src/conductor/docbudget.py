"""Repo docs and their size budget (`doc_budget_kb`): which files count, their sizes for the
digest's **due** doc trim (`session.doc_sizes`), and the prompt section that shows an item
touching one the bar it is held to (151: fractals 023 measured ~20 cuts by hand, the budget
only in the planner's digest)."""

from __future__ import annotations

import re
from pathlib import Path

from . import git, globs
from .config import Config

GENERATED_RE = re.compile(rb"\bgenerated\b[^\n]{0,80}\b(by|from|with)\b|\bdo not edit\b", re.IGNORECASE)
GENERATED_HEAD = 1024       # a generated doc says so near its top

# An item body naming a trim or a budget gets the section; so does one naming an over-budget doc.
TRIM_RE = re.compile(r"\btrim|\b(doc|size) budget|\bdoc[- ]size|\b\d+ ?KB\b", re.IGNORECASE)

SECTION = """
## Doc budget

A repo doc (`.md` at the root or under `docs/`, any `README.md` or `CLAUDE.md`) is held to
{kb:g} KB, 1 KB = 1,024 bytes: at most {limit:,} bytes (`wc -c <file>`; generated docs{exempt}
exempt). Over it on main now: {over}. A trim brings each doc it touches under the bar, and
the report gives each one's bytes before and after.
"""


def is_doc(rel: str) -> bool:
    """A repo's own docs: `.md` at its root or under `docs/`, or a `README.md` or `CLAUDE.md`
    anywhere. Reports under a results folder are output (aicomplete has ~40 past 15 KB)."""
    parts = rel.split("/")
    return parts[-1].lower().endswith(".md") and (
        len(parts) == 1 or parts[0] == "docs" or parts[-1] in ("README.md", "CLAUDE.md"))


def is_generated(path: Path) -> bool:
    """A doc that says near its top it is generated ("Generated by `cards_doc.py` ... do
    not edit"): its size is its source's, so no trim is due (aicomplete 133, 84)."""
    try:
        with open(path, "rb") as fh:
            return bool(GENERATED_RE.search(fh.read(GENERATED_HEAD)))
    except OSError:
        return False


def repo_sizes(cfg: Config, repo: str) -> dict[str, int]:
    """Bytes of each tracked doc of `repo` in its main checkout (`is_doc`, not `is_generated`,
    not matching its `doc_budget_exempt` globs: aicomplete's adversary cards, 86), by path."""
    root = cfg.repos[repo]
    try:
        paths = git.ls_files(root)
    except (OSError, git.GitError):
        return {}
    exempt = cfg.opts(repo).doc_budget_exempt
    out = {}
    for rel in paths:
        if any(globs.matches(rel, g) for g in exempt):
            continue
        if is_doc(rel) and (p := root / rel).is_file() and not is_generated(p):
            out[rel] = p.stat().st_size
    return out


def section(cfg: Config, repo: str, body: str) -> str:
    """The prompt's *Doc budget* section, for an item whose body names a trim or budget, or a
    doc over budget now; else nothing."""
    limit = int(cfg.doc_budget_kb * 1024)
    sizes = repo_sizes(cfg, repo)
    over = {rel: n for rel, n in sizes.items() if n > limit}
    if not (TRIM_RE.search(body) or any(rel in body for rel in over)):
        return ""
    exempt = cfg.opts(repo).doc_budget_exempt
    return SECTION.format(kb=cfg.doc_budget_kb, limit=limit,
                          exempt=f" and {', '.join(f'`{g}`' for g in exempt)}" if exempt else "",
                          over=", ".join(f"`{rel}` {n:,}" for rel, n in sorted(over.items())) or "none")
